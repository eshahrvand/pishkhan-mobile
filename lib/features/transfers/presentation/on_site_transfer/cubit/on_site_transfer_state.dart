part of 'on_site_transfer_cubit.dart';

enum OnSiteTransferStep { source, visit, destinations, confirmation }

enum OnSiteTransferEffect {
  addressEditor,
  deleteAddress,
  destinationEditor,
  uploadSheet,
  pickFile,
  closeDestination,
  reveal,
  confirmExit,
  back,
  home,
  assistant,
  unavailable,
  receipt,
}

@Freezed(toStringOverride: false)
abstract class OnSiteTransferState with _$OnSiteTransferState {
  const factory OnSiteTransferState.initial({
    @Default(OnSiteTransferStep.source) OnSiteTransferStep step,
    @Default(1) int stepNumber,
    @Default(RequestStatus.initial) RequestStatus catalogStatus,
    @Default(RequestStatus.initial) RequestStatus destinationStatus,
    @Default(RequestStatus.initial) RequestStatus uploadStatus,
    @Default(RequestStatus.initial) RequestStatus submissionStatus,
    TransferCatalog? catalog,
    TransferDeposit? deposit,
    @Default('') String transferDateInput,
    DateTime? transferDate,
    @Default(false) bool isTransferDateValid,
    @Default(false) bool isTransferDateError,
    @Default('') String visitDateInput,
    DateTime? visitDate,
    @Default(false) bool isVisitDateValid,
    @Default(false) bool isVisitDateError,
    @Default(<DeliveryAddress>[]) List<DeliveryAddress> addresses,
    DeliveryAddress? address,
    @Default(<TransferDestination>[]) List<TransferDestination> destinations,
    @Default('') String amountInput,
    @Default(0) int amountRial,
    @Default(false) bool isAmountValid,
    @Default(false) bool isAmountError,
    TransferMethod? method,
    @Default('') String ibanInput,
    @Default(false) bool isIbanValid,
    @Default(false) bool isIbanError,
    TransferPurpose? purpose,
    @Default('') String description,
    @Default(false) bool canAddDestination,
    @Default('') String uploadName,
    @Default(0) int uploadSizeBytes,
    @Default(0.0) double uploadProgress,
    @Default(0) int filePickerRequestId,
    TransferAttachment? pendingAttachment,
    TransferAttachment? attachment,
    @Default(false) bool canReviewFile,
    @Default(false) bool canContinue,
    @Default(false) bool termsAccepted,
    @Default(false) bool isWalletSufficient,
    @Default(true) bool isSummaryExpanded,
    @Default(false) bool isInvoiceExpanded,
    OnSiteTransferRequest? confirmedRequest,
    TransferReceipt? receipt,
    Failure? catalogFailure,
    Failure? destinationFailure,
    Failure? uploadFailure,
    Failure? submissionFailure,
    OnSiteTransferEffect? effect,
    @Default(0) int effectId,
  }) = _OnSiteTransferState;
}
