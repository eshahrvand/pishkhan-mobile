part of 'loan_request_cubit.dart';

enum LoanRequestEffect {
  creditInfo,
  installments,
  insurance,
  contract,
  otp,
  receipt,
  confirmCancel,
  confirmExit,
  exit,
  unavailable,
  copyRequestNumber,
}

@Freezed(toStringOverride: false)
abstract class LoanRequestState with _$LoanRequestState {
  const factory LoanRequestState.initial({
    @Default(LoanApplicationStep.introduction) LoanApplicationStep step,
    @Default(1) int stepNumber,
    @Default(RequestStatus.initial) RequestStatus catalogStatus,
    @Default(RequestStatus.initial) RequestStatus quoteStatus,
    @Default(RequestStatus.initial) RequestStatus inquiryStatus,
    @Default(RequestStatus.initial) RequestStatus guarantorStatus,
    @Default(RequestStatus.initial) RequestStatus collateralStatus,
    @Default(RequestStatus.initial) RequestStatus draftStatus,
    @Default(RequestStatus.initial) RequestStatus otpStatus,
    @Default(RequestStatus.initial) RequestStatus submissionStatus,
    @Default(RequestStatus.initial) RequestStatus cancellationStatus,
    LoanCatalog? catalog,
    int? draftRemainingSeconds,
    LoanDeposit? deposit,
    @Default(LoanRepayment.installments) LoanRepayment repayment,
    @Default(500000000) int amountRial,
    @Default(10) int months,
    double? amountPosition,
    double? monthsPosition,
    @Default(1) int minimumMonths,
    @Default(60) int maximumMonths,
    LoanQuote? quote,
    LoanCreditAssessment? assessment,
    @Default(<LoanInquiry>[]) List<LoanInquiry> inquiries,
    @Default('') String guarantorNationalId,
    @Default(false) bool isGuarantorIdValid,
    @Default(false) bool isGuarantorIdError,
    LoanGuarantor? guarantor,
    @Default(false) bool canCheckGuarantor,
    @Default(false) bool canRetryInquiries,
    @Default(LoanInstrument.promissoryNote) LoanInstrument ownInstrument,
    @Default(LoanInstrument.promissoryNote) LoanInstrument guarantorInstrument,
    @Default('') String ownNumber,
    @Default('') String guarantorNumber,
    @Default(false) bool isOwnNumberValid,
    @Default(false) bool isOwnNumberError,
    @Default(false) bool isGuarantorNumberValid,
    @Default(false) bool isGuarantorNumberError,
    @Default(false) bool isCollateralError,
    LoanCollateral? collateral,
    LoanDraft? draft,
    @Default(true) bool isSummaryExpanded,
    @Default(true) bool isCreditExpanded,
    @Default(false) bool termsAccepted,
    @Default(false) bool isInsuranceSelected,
    LoanSigningChallenge? challenge,
    @Default('') String otp,
    @Default(false) bool isOtpValid,
    @Default(false) bool isOtpError,
    @Default(0) int remainingSeconds,
    @Default(false) bool canSubmit,
    @Default(false) bool canContinue,
    LoanRecord? receipt,
    LoanRequestEffect? effect,
    Failure? failure,
    String? message,
  }) = _LoanRequestState;
}
